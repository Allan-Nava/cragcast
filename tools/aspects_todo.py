#!/usr/bin/env python3
"""CG-16: write docs/aspects-todo.md — every crag in data/crags.json that has no
climbing:orientation on OpenStreetMap, by province, with the link to edit it on OSM.
Rerun after data/crags.json changes (the monthly refresh, or a run of osm_crags.py):

    python3 tools/aspects_todo.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CRAGS = ROOT / "data" / "crags.json"
TARGET = ROOT / "docs" / "aspects-todo.md"


def edit_url(source_url):
    m = re.search(r"openstreetmap\.org/(node|way|relation)/(\d+)", source_url)
    return f"https://www.openstreetmap.org/edit?{m.group(1)}={m.group(2)}" if m else None


def main():
    crags = json.loads(CRAGS.read_text())["crags"]
    todo = [c for c in crags if not c.get("aspect")]
    done = [c for c in crags if c.get("aspect")]
    by_province = {}
    for c in todo:
        by_province.setdefault(c.get("province") or "Provincia sconosciuta", []).append(c)

    lines = [
        "# Wall aspects to map on OpenStreetMap (CG-16)",
        "",
        "Generated by `tools/aspects_todo.py` from `data/crags.json` — do not edit by hand.",
        "",
        f"**{len(done)} of {len(crags)} crags** have `climbing:orientation`. Without it cragcast",
        "judges a wall as shaded, the cautious reading, so a sunny wall gets a stricter verdict",
        "after rain than it deserves.",
        "",
        "## How to add it",
        "",
        "Only for a crag you know first-hand — OpenStreetMap does not accept data copied from",
        "guidebooks or websites under copyright.",
        "",
        "1. Open **edit** next to the crag (log in to OpenStreetMap; the iD editor opens on it).",
        "2. In the tag list, add `climbing:orientation` with where the wall faces:",
        "   `N`, `NE`, `E`, `SE`, `S`, `SW`, `W` or `NW` (English letters: SW, not SO).",
        "3. Save with a comment such as \"climbing:orientation from a visit\".",
        "",
        "The aspect reaches cragcast with the monthly refresh of the crag list (`crags-refresh.yml`,",
        "on the 1st), or at once if the workflow is run by hand.",
        "",
        "A crag mapped on OSM needs a name and either `climbing=crag` or `sport=climbing` on a cliff,",
        "a rock or a climbing site to be in cragcast; a sector mapped on its own (\"Settore Alto\")",
        "is folded into the crag around it. Tagging the crag itself `climbing=crag` is the clearest.",
        "",
    ]
    for province in sorted(by_province, key=lambda p: p.lower()):
        rows = sorted(by_province[province], key=lambda c: c["name"].lower())
        lines += [f"## {province} ({len(rows)})", "", "| Crag | Municipality | Elevation | OSM | |", "|---|---|---|---|---|"]
        for c in rows:
            elev = f"{c['elevation']} m" if c.get("elevation") is not None else ""
            edit = edit_url(c["sourceUrl"])
            lines.append(f"| {c['name']} | {c.get('municipality') or ''} | {elev} | "
                         f"[view]({c['sourceUrl']}) | {f'[edit]({edit})' if edit else ''} |")
        lines.append("")
    lines += ["## Already mapped", ""]
    lines += [f"- {c['name']} ({c.get('municipality') or ''}): {c['aspect']}"
              for c in sorted(done, key=lambda c: c["name"].lower())]
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text("\n".join(lines) + "\n")
    print(f"{len(todo)} crags without an aspect written to {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
